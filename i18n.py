class Message(str):
    """A string-compatible canonical Chinese message with lossless parameters."""

    def __new__(cls, template, **values):
        obj = super().__new__(cls, template.format(**values) if values else template)
        obj.source, obj.values = template, values
        return obj

    def render(self, language="zh"):
        template = EN.get(self.source, self.source) if language == "en" else self.source
        values = {key: value.render(language) if isinstance(value, Message) else value
                  for key, value in self.values.items()}
        return template.format(**values) if values else template

    def __reduce__(self):
        return message_from_payload, (self.to_payload(),)

    def to_payload(self):
        return {"source": self.source, "values": {
            key: {"message": value.to_payload()} if isinstance(value, Message) else value
            for key, value in self.values.items()}}


def message_from_payload(payload):
    return Message(payload["source"], **{
        key: message_from_payload(value["message"]) if isinstance(value, dict) and set(value) == {"message"} else value
        for key, value in payload.get("values", {}).items()})


def message(template, **values):
    return Message(template, **values)


def render(value, language="zh"):
    if isinstance(value, Message):
        return value.render(language)
    return EN.get(str(value), str(value)) if language == "en" else str(value)


def exception_message(exc):
    """Keep structured exception parameters; translate only owned literals."""
    if len(exc.args) == 1 and isinstance(exc.args[0], Message):
        return exc.args[0]
    text = str(exc)
    return Message(text) if text in EN else text
