class MessageTests(unittest.TestCase):
    def test_nested_messages_do_not_translate_parameter_data(self):
        value = message("已生成不可变数据版本：{path}", path="F:/原图/草稿/已审核.json")
        self.assertIn("Created an immutable", render(value, "en"))
        self.assertIn("F:/原图/草稿/已审核.json", render(value, "en"))
        self.assertIn("已生成", render(value, "zh"))

    def test_copy_and_serialization_preserve_nested_templates(self):
        value = message("训练失败：{kind}: {error}", kind="ValueError",
                        error=message("{what}不能为空、过长或包含控制字符", what=message("场景组")))
        for copy in (deepcopy(value), message_from_payload(json.loads(json.dumps(value.to_payload(), ensure_ascii=False)))):
            self.assertIsInstance(copy, Message)
            self.assertEqual(render(copy, "en"), "Training failed: ValueError: Scene group cannot be empty, too long, or contain control characters.")

    def test_exception_literals_and_dynamic_parameters_are_localized(self):
        self.assertEqual(render(exception_message(ValueError("输入图像为空")), "en"), "The input image is empty.")
        exception = ValueError(message("本图需要 {count} 块，超过 {maximum} 块上限；请增大切片或缩小输入图像。", count=16, maximum=9))
        self.assertIn("16 slices (limit 9)", render(exception_message(exception), "en"))
        self.assertEqual(render(exception_message(OSError("native error: F:/原图")), "en"), "native error: F:/原图")

    def test_catalog_preserves_all_format_fields(self):
        fields = lambda text: {(name, spec, conversion) for _, name, spec, conversion in Formatter().parse(text) if name is not None}
        for source, english in EN.items():
            with self.subTest(source=source):
                self.assertEqual(fields(source), fields(english))
                if source != "语言 / Language:":
                    self.assertFalse(HAN.search(english), source)

    def test_all_static_gui_text_has_a_catalog_entry(self):
        for name in ("main.py", "ui.py", "feedback_ui.py", "auto_annotation_ui.py", "compare_ui.py"):
            tree = ast.parse((PROJECT/name).read_text(encoding="utf-8"))
            for node in ast.walk(tree):
                if isinstance(node, ast.Constant) and isinstance(node.value, str) and HAN.search(node.value):
                    with self.subTest(file=name, line=node.lineno, text=node.value):
                        # Exact comparison of the historical autogenerated model title.
                        if node.value != "（纠错型·":
                            self.assertIn(node.value, EN)

    def test_runtime_errors_and_message_templates_have_catalog_entries(self):
        for name in ("engines.py", "visual_engine.py", "enhancement.py", "resource_safety.py",
                     "sliced_inference.py", "feedback.py", "feedback_training.py", "video_worker.py", "live_video.py", "prompt_modes.py", "modified_models.py",
                     "auto_annotation.py", "detection_branch.py"):
            tree = ast.parse((PROJECT/name).read_text(encoding="utf-8"))
            for node in ast.walk(tree):
                if isinstance(node, ast.Raise) and isinstance(node.exc, ast.Call):
                    literals = [node.exc.args[0]] if node.exc.args else []
                elif isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "message":
                    literals = node.args[:1]
                else:
                    continue
                for value in literals:
                    if isinstance(value, ast.Constant) and isinstance(value.value, str) and HAN.search(value.value):
                        with self.subTest(file=name, line=value.lineno):
                            self.assertIn(value.value, EN)


class LanguageUiTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.application = QApplication.instance() or QApplication([])
        from main import AIApp
        cls.AIApp = AIApp

    def setUp(self):
        self.window = self.AIApp()
        from feedback import FeedbackStore
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.window.feedback_panel.store = FeedbackStore(Path(directory.name)/"feedback")
        self.window.feedback_panel.refresh()
        self.window.show()
        self.application.processEvents()

    def tearDown(self):
        self.window.worker = None
        self.window.training_active = False
        self.window.feedback_panel.process = None
        self.window.feedback_panel.dirty = False
        self.window.close()
        self.window.deleteLater()
        QCoreApplication.sendPostedEvents(None, QEvent.DeferredDelete)

    def switch(self, language):
        self.window.language_combo.setCurrentIndex(self.window.language_combo.findData(language))
        self.application.processEvents()

    def test_selector_is_visible_on_every_page_even_when_settings_scroll(self):
        window = self.window
        scrollbar = window.settings_scroll.verticalScrollBar()
        scrollbar.setValue(scrollbar.maximum())
        for index in range(window.tabs.count()):
            window.tabs.setCurrentIndex(index)
            self.application.processEvents()
            self.assertTrue(window.language_combo.isVisible())
            self.assertLess(window.language_combo.mapTo(window, window.language_combo.rect().topLeft()).y(), 65)
        self.switch("en")
        self.assertEqual([window.tabs.tabText(index) for index in range(4)],
            ["1. Prompt-free / Text detection", "2. Visual prompts", "3. Corrections / Fine-tuning", "4. Auto-labeling"])
        self.assertIn("YOLO txt or COCO json", " ".join(label.text() for label in window.tabs.widget(3).findChildren(QLabel)))
        self.switch("zh")
        self.assertEqual(window.tabs.tabText(0), "1. 无提示 / 开放文本检测")

